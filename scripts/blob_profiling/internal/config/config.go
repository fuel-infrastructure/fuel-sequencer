func RunOutputDir(timestamp time.Time) string {
	return timestamp.Format("2006-01-02_T_15_04_05")
}

// Profile defines the approach of the profiler for the generation of blobs
// - If both Duration and MaxRate are defined, the profile until any condition is reached
// - If Duration is not set, the profile will run until the MaxRate is reached
// -If MaxRate is not set, the profile will run for the duration set by Duration
// - If neither is set, it will run indefinitely
type Profile struct {
	Description string `json:"description"` // Description of the profile, to be used for the output data
	// Duration is the duration the profile is allowed to run for
	time.Duration `json:"duration"`
	// MaxRate is the maximum rate of bytes/sec that the profiler will try to reach before stopping
	MaxRate int `json:"max_rate"` // bytes/sec
	// Rate is the bytes/sec rate at which of that the profiler will try to match ongoing throughput
	Rate func(since time.Duration) int `json:"rate"` // bytes/sec
	// Size is the total size of all blobs that the profiler intends to have generated by the time since the start
	// This is the integral of the Rate function (area under the curve)
	Size func(since time.Duration) int `json:"size"` // bytes

	// Enhanced metadata for visualization context
	Type         string `json:"profile_type"`        // Type of profile (e.g., "constant", "linear", "exponential")
	Purpose      string `json:"profile_purpose"`     // Purpose/intent of this profile
	Explanation  string `json:"profile_explanation"` // Detailed explanation of what this profile tests
	BlobSizeInfo string `json:"blob_size_info"`      // Information about blob size distribution
}

// Config holds the profiler configuration
type Config struct {
	BlobhubURL       string                       `json:"blobhub_url"`   // Blobhub URL, the main shared instance for blob storage
	SequencerRPC     string                       `json:"sequencer_rpc"` // Sequencer RPC URL, an instance of the sequencer
	BlobpoolURL      string                       `json:"blobpool_url"`  // Blobpool URL, an instance of the blob-storage server, coupled to the sequencer's blobpool
	ParquetDir       string                       `json:"parquet_dir"`   // Directory to output measurement data as parquet files
	Profile          `json:"profile"`             // Profile configuration, including duration, max rate, rate function, and size function
	BlobDistribution blobgen.BlobSizeDistribution `json:"blob_distribution"` // Blob size distribution, used to generate blobs
	MaxLagRatio      float32                      `json:"max_lag_ratio"`     // When to consider actual throughput as lagging the planned throughput rate
	LagTolerance     time.Duration                `json:"lag_tolerance"`     // How long to tolerate throughput lagging before considering it as a failure
	BufferDuration   time.Duration                `json:"buffer_duration"`   // Duration as buffer to keep generated blobs before submitting
	Topic            string                       `json:"topic"`
	Sender           string                       `json:"sender"`
}

// SetBlobDistribution sets the blob distribution and appends blob size info to the purpose
func (c *Config) SetBlobDistribution(distribution blobgen.BlobSizeDistribution) {
	c.BlobDistribution = distribution
	blobInfo := GenerateBlobSizeInfo(distribution)
	c.Purpose = c.Purpose + " | " + blobInfo

	// Update the profile description to include the blob size info
	c.Profile.Description = c.Profile.Description + "_with_" +
		strings.ReplaceAll(strings.ToLower(blobInfo), " ", "_")
}

// Configuration validation errors
var (
	ErrEmptyBlobhubURL       = errors.New("blobhub URL cannot be empty")
	ErrEmptySequencerRPC     = errors.New("sequencer RPC address cannot be empty")
	ErrEmptyBlobpoolURL      = errors.New("blobpool URL cannot be empty")
	ErrInvalidDuration       = errors.New("invalid duration: must be positive")
	ErrNilRateFunction       = errors.New("invalid profile rate function: must be non-nil")
	ErrNilSizeFunction       = errors.New("invalid profile size function: must be non-nil")
	ErrInvalidMaxRate        = errors.New("invalid profile max rate: must be positive")
	ErrInvalidMaxLagRatio    = errors.New("invalid max lag ratio: must be positive")
	ErrInvalidLagTolerance   = errors.New("invalid lag tolerance: must be positive")
	ErrInvalidBufferDuration = errors.New("invalid buffer duration: must be positive")
)

// Validate checks if the configuration is valid
func (c *Config) Validate() error {
	if c.BlobhubURL == "" {
		return ErrEmptyBlobhubURL
	}
	if c.SequencerRPC == "" {
		return ErrEmptySequencerRPC
	}
	if c.BlobpoolURL == "" {
		return ErrEmptyBlobpoolURL
	}
	if c.Duration < 0 {
		return ErrInvalidDuration
	}
	if c.MaxRate < 0 {
		return ErrInvalidMaxRate
	}
	if c.Rate == nil {
		return ErrNilRateFunction
	}
	if c.Size == nil {
		return ErrNilSizeFunction
	}
	if c.MaxRate <= 0 {
		return ErrInvalidMaxRate
	}
	if err := blobgen.ValidateDistribution(c.BlobDistribution); err != nil {
		return err
	}
	if c.MaxLagRatio <= 0.0 {
		return ErrInvalidMaxLagRatio
	}
	if c.LagTolerance <= 0 {
		return ErrInvalidLagTolerance
	}
	if c.BufferDuration <= 0 {
		return ErrInvalidBufferDuration
	}
	return nil
}

// GenerateBlobSizeInfo creates a concise description of the blob size distribution
func GenerateBlobSizeInfo(distribution blobgen.BlobSizeDistribution) string {
	// Simple approach - only handle known distributions, fail fast for others
	switch {
	case distribution == blobgen.Fixed10KiB:
		return "10 KiB blobs"
	case distribution == blobgen.Fixed100KiB:
		return "100 KiB blobs"
	case distribution == blobgen.Fixed1MiB:
		return "1 MiB blobs"
	case distribution == blobgen.Fixed10MiB:
		return "10 MiB blobs"
	case distribution == blobgen.RealisticDistribution:
		return "Distributed blobs"
	default:
		// Fail fast for undefined distributions
		panic(fmt.Sprintf("unsupported blob size distribution: %T", distribution))
	}
}

// ProfilerReport represents the structure of the profiler_report.json file
type ProfilerReport struct {
	Environment struct {
		Config struct {
			Profile struct {
				Description        string `json:"description"`
				Duration           int64  `json:"duration"`
				MaxRate            int64  `json:"max_rate"`
				ProfileType        string `json:"profile_type"`
				ProfilePurpose     string `json:"profile_purpose"`
				ProfileExplanation string `json:"profile_explanation"`
				BlobSizeInfo       string `json:"blob_size_info"`
			} `json:"profile"`
			BlobDistribution int `json:"blob_distribution"`
		} `json:"config"`
	} `json:"environment"`
}

// GetProfileFromDir extracts profile information from a directory path
// This is used for visualization-only mode to determine the profile type from existing data
func GetProfileFromDir(dirPath string) Profile {
	// Try to read from profiler_report.json first
	reportPath := filepath.Join(dirPath, "profiler_report.json")
	if data, err := os.ReadFile(reportPath); err == nil {
		var report ProfilerReport
		if err := json.Unmarshal(data, &report); err == nil {
			profile := report.Environment.Config.Profile

			// Determine explanation based on profile type
			var explanation string
			switch profile.ProfileType {
			case "constant":
				explanation = "Maintains a steady, constant throughput rate throughout the test duration"
			case "linear":
				explanation = "Gradually increases throughput rate linearly over time to test system scalability"
			case "exponential":
				explanation = "Exponentially increases throughput rate to find system breaking points"
			default:
				explanation = profile.ProfileExplanation
			}

			// Get blob size info from blob distribution
			var blobSizeInfo string
			switch report.Environment.Config.BlobDistribution {
			case 0: // Fixed10KiB
				blobSizeInfo = "10 KiB blobs"
			case 1: // Fixed100KiB
				blobSizeInfo = "100 KiB blobs"
			case 2: // Fixed1MiB
				blobSizeInfo = "1 MiB blobs"
			case 3: // Fixed10MiB
				blobSizeInfo = "10 MiB blobs"
			case 4: // RealisticDistribution
				blobSizeInfo = "Distributed blobs"
			default:
				blobSizeInfo = profile.BlobSizeInfo
			}

			return Profile{
				Description:  profile.Description,
				Type:         profile.ProfileType,
				Purpose:      profile.ProfilePurpose,
				Explanation:  explanation,
				BlobSizeInfo: blobSizeInfo,
			}
		}
	}

	// Fallback to directory name parsing if profiler_report.json is not available
	// Extract the directory name from the path
	dirName := filepath.Base(dirPath)

	// Parse the directory name to extract profile information
	// Expected format: "linear_10_kib_per_s_for_600_secs_with_1_mib_blobs"
	parts := strings.Split(dirName, "_")

	if len(parts) < 2 {
		return Profile{}
	}

	// Determine profile type from the first part
	var profileType, purpose, explanation string
	switch parts[0] {
	case "constant":
		profileType = "constant"
		purpose = "Constant Load Testing"
		explanation = "Maintains a steady, constant throughput rate throughout the test duration"
	case "linear":
		profileType = "linear"
		purpose = "Linear Load Testing"
		explanation = "Gradually increases throughput rate linearly over time to test system scalability"
	case "exponential":
		profileType = "exponential"
		purpose = "Exponential Stress Testing"
		explanation = "Exponentially increases throughput rate to find system breaking points"
	default:
		profileType = "unknown"
		purpose = "Unknown Profile"
		explanation = "Profile type could not be determined from directory name"
	}

	// Extract blob size information
	var blobSizeInfo string
	if strings.Contains(dirName, "10_kib_blobs") {
		blobSizeInfo = "10 KiB blobs"
	} else if strings.Contains(dirName, "100_kib_blobs") {
		blobSizeInfo = "100 KiB blobs"
	} else if strings.Contains(dirName, "1_mib_blobs") {
		blobSizeInfo = "1 MiB blobs"
	} else if strings.Contains(dirName, "10_mib_blobs") {
		blobSizeInfo = "10 MiB blobs"
	} else if strings.Contains(dirName, "distributed_blobs") {
		blobSizeInfo = "Distributed blobs"
	} else {
		blobSizeInfo = "Unknown blob sizes"
	}

	return Profile{
		Description:  dirName,
		Type:         profileType,
		Purpose:      purpose,
		Explanation:  explanation,
		BlobSizeInfo: blobSizeInfo,
	}
}
